// Every environment variable Lictory's runtime code reads, in one list. The
// API, worker and migration runner validate their share at startup
// (`@lictory/core/config/validate`); docs/operations/configuration.md is
// generated from this list (`bun run config:docs`), and tests fail when code
// reads a variable that is not declared here.

/** A process or build that reads configuration. */
export type Service =
  | "api"
  | "worker"
  | "migrate"
  | "platform"
  | "website"
  | "edge-proxy"
  | "rebuild-projections";

/** Services that validate their configuration when they start. */
export type ValidatedService = Extract<Service, "api" | "worker" | "migrate">;

export const services: Record<Service, string> = {
  api: "HTTP API (`apps/api`)",
  worker: "Background worker (`apps/worker`)",
  migrate: "Migration runner (`bun run db:migrate`, the `migrate` image)",
  platform:
    "Platform SPA build and Vite dev server (`apps/platform`); values are embedded at build time",
  website:
    "Marketing website (`apps/marketing`); most values are embedded at build time",
  "edge-proxy":
    "Local single-origin proxy for development and browser tests (`scripts/edge-proxy.ts`)",
  "rebuild-projections":
    "Operator script that rebuilds read projections (`scripts/rebuild-projections.ts`)",
};

/** How a set value is checked at startup. Unchecked when omitted. */
export type Value =
  | { type: "integer"; minimum?: number }
  | { type: "boolean" }
  | { type: "origin" }
  | { type: "choice"; values: readonly string[] };

export type Secret =
  /** Generated by the operator (`openssl rand -hex 32`): at least 32 bytes in production. */
  | "generated"
  /** Issued by a provider (API keys, OAuth client secrets, passwords in URLs). */
  | "issued";

export type Declaration = {
  name: string;
  group: string;
  services: readonly Service[];
  /**
   * `always`: these services refuse to start without it. `production`: only
   * when NODE_ENV=production. Applies to `requiredBy` (default: every
   * validated service in `services`).
   */
  required?: "always" | "production";
  requiredBy?: readonly ValidatedService[];
  /** What applies when unset (blank counts as unset), as Markdown for the reference. */
  default?: string;
  secret?: Secret;
  value?: Value;
  description: string;
};

