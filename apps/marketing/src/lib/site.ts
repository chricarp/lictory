export type PublicPage = {
  path: string;
  title: string;
  description: string;
  changeFrequency: "weekly" | "monthly" | "yearly";
  priority: number;
  /** Only for pages whose last change is known; never a build timestamp. */
  lastModified?: string;
};

const latest = (dates: readonly string[]) => [...dates].sort().at(-1)!;

