// Generates docs/operations/configuration.md from the configuration
// declarations (packages/core/src/config/declarations.ts).
// Usage: bun run config:docs            rewrite the reference
//        bun scripts/configuration-reference.ts --check   fail when it is stale
import { readFile, writeFile } from "node:fs/promises";

import { format, resolveConfig } from "prettier";

import {
  declarations,
  services,
  type Declaration,
  type ValidatedService,
} from "@lictory/core/config/declarations";

const output = "docs/operations/configuration.md";
const validated: readonly ValidatedService[] = ["api", "worker", "migrate"];

// Variable names outside code spans become code spans.
function prose(text: string) {
  return text
    .split("`")
    .map((part, index) =>
      index % 2 === 1
        ? `\`${part}\``
        : part.replace(
            /\b[A-Z][A-Z0-9]*_[A-Z0-9_]+\b/g,
            (name) => `\`${name}\``,
          ),
    )
    .join("")
    .replaceAll("|", "\\|");
}

function required(declaration: Declaration) {
  if (!declaration.required) return "No";
  const by =
    declaration.requiredBy ??
    validated.filter((s) => declaration.services.includes(s));
  const when = declaration.required === "always" ? "Yes" : "In production";
  return `${when} (${by.join(", ")})`;
}

function secret(declaration: Declaration) {
  if (declaration.secret === "generated") return "Yes, ≥ 32 bytes";
  if (declaration.secret === "issued") return "Yes";
  return "No";
}

function render() {
  const groups = new Map<string, Declaration[]>();
  for (const d of declarations)
    groups.set(d.group, [...(groups.get(d.group) ?? []), d]);
  const lines = [
    "# Configuration reference",
    "",
    "<!-- Generated by `bun run config:docs` from packages/core/src/config/declarations.ts. Do not edit by hand: `bun run check` fails when this file is out of date. -->",
    "",
    "Every environment variable Lictory's runtime code reads. The API, the worker",
    "and the migration runner check their variables when they start and stop with",
    "every problem listed at once; tests fail when code reads a variable that is",
    "not declared. Empty or whitespace-only values count as unset, so a deployment",
    "that forwards every variable still gets the defaults.",
    "",
    "Where to set them: [`.env.example`](../../.env.example) for local development,",
    "[`deploy/env/production.env.example`](../../deploy/env/production.env.example)",
    "and [`deploy/compose.production.yaml`](../../deploy/compose.production.yaml) for",
    "a server (Compose maps a few names: `ZERO_API_KEY` becomes both Zero keys,",
    "`APP_HOST` becomes `PLATFORM_URL`). Deployment-only settings (hosts, database",
    "passwords, backups, sizing) are described in those files and in",
    "[deployment](./deployment.md); zero-cache's own `ZERO_*` settings follow",
    "[Rocicorp Zero's documentation](https://zero.rocicorp.dev/docs).",
    "",
    "## Production rules",
    "",
    "With `NODE_ENV=production` (set by the production images):",
    "",
    "- Variables marked _In production_ are required.",
    "- A secret must not be a placeholder from an example file or runbook (for",
    "  example `.env.example`'s `BETTER_AUTH_SECRET` value, or `generate` left over",
    "  from `deploy/env/*.env.example`).",
    "- Generated secrets need at least 32 bytes. Use `openssl rand -hex 32`.",
    "- Outside production the same checks for missing required values, whole",
    "  numbers, origins and choices apply; secrets are not checked.",
    "",
    "Development fallbacks (`BETTER_AUTH_URL`, `localhost` origins) apply only",
    "outside production.",
    "",
    "## Delivery credentials key",
    "",
    "`DELIVERY_CREDENTIALS_KEY` encrypts stored Jira API tokens. Without it the key",
    "is derived from `BETTER_AUTH_SECRET`, which ties rotating one to the other.",
    "",
    "- **New installations** must set it before connecting Jira. In production,",
    "  connecting Jira is refused while the key is unset and no delivery",
    "  credentials are stored yet (no `delivery_connection` row exists, including",
    "  archived ones). The rest of Lictory works without it.",
    "- **Existing installations** that already stored credentials with the derived",
    "  key keep working unchanged. The API and the worker log a `config.warning` at",
    "  startup. To decouple the two secrets without re-entering tokens, set",
    "  `DELIVERY_CREDENTIALS_KEY` to the current `BETTER_AUTH_SECRET` value (it",
    "  derives the same key); `BETTER_AUTH_SECRET` can then rotate on its own.",
    "- Never rotate `DELIVERY_CREDENTIALS_KEY` once credentials are stored: they",
    "  become unreadable and every Jira connection must be reconnected.",
    "",
    "## Services",
    "",
    "| Service | What it is |",
    "| --- | --- |",
    ...Object.entries(services).map(
      ([name, description]) => `| ${name} | ${prose(description)} |`,
    ),
  ];
  for (const [group, entries] of groups) {
    lines.push(
      "",
      `## ${group}`,
      "",
      "| Variable | Required | Default | Read by | Secret | Description |",
      "| --- | --- | --- | --- | --- | --- |",
      ...entries.map(
        (d) =>
          `| \`${d.name}\` | ${required(d)} | ${d.default ? prose(d.default) : ""} | ${d.services.join(", ")} | ${secret(d)} | ${prose(d.description)} |`,
      ),
    );
  }
  return `${lines.join("\n")}\n`;
}

const options = await resolveConfig(output);
const expected = await format(render(), { ...options, filepath: output });

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== expected) {
    console.error(
      `${output} is out of date with packages/core/src/config/declarations.ts. Run: bun run config:docs`,
    );
    process.exit(1);
  }
} else {
  await writeFile(output, expected);
  console.log(`Wrote ${output}`);
}
