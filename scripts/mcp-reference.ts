// ------------------------------------------------------------ JSON schema

type Schema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  items?: Schema;
  anyOf?: Schema[];
  oneOf?: Schema[];
  properties?: Record<string, Schema>;
  required?: string[];
  description?: string;
  format?: string;
  default?: unknown;
};

function typeOf(schema: Schema): string {
  if (schema.enum)
    return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(", ");
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  const variants = schema.anyOf ?? schema.oneOf;
  if (variants) return [...new Set(variants.map(typeOf))].join(" or ");
  if (Array.isArray(schema.type)) return schema.type.join(" or ");
  if (schema.type === "array")
    return schema.items ? `list of ${typeOf(schema.items)}` : "list";
  if (schema.type === "string" && schema.format === "uuid") return "id";
  if (schema.type === "string" && schema.format) return schema.format;
  return schema.type ?? "any";
}

function describe(schema: Schema): string {
  const own =
    schema.description ??
    (schema.anyOf ?? schema.oneOf ?? []).find((s) => s.description)
      ?.description ??
    "";
  return own;
}

// ------------------------------------------------------------- tool pages

const decisions = new Map(
  personDecisionOperations(capabilities).map((o) => [o.name, o]),
);

function facts(capability: AnyCapability, schema: Schema) {
  const facts: string[] = [
    capability.kind === "query" ? "Query (read tokens too)" : "Command",
  ];
  if (capability.kind === "command") {
    const properties = schema.properties ?? {};
    facts.push(
      "mutationId" in properties
        ? "retry key `mutationId`"
        : capability.idempotent
          ? "safe to repeat"
          : "no retry key: read before repeating",
    );
  }
  if (capability.destructive) facts.push("destructive");
  if (capability.external) facts.push("talks to an outside system");
  const decision = decisions.get(capability.name);
  if (decision)
    facts.push(
      `**a person's decision**: refused to agents (the person decides in ${decision.where})`,
    );
  return facts.join(" · ");
}

function tool(capability: AnyCapability) {
  const schema = inputSchemaOf(capability) as Schema;
  const properties = Object.entries(schema.properties ?? {});
  const required = new Set(schema.required ?? []);
  const lines = [
    `### \`${capability.name}\``,
    "",
    `**${prose(capability.title)}.** ${facts(capability, schema)}`,
    "",
    linked(capability.description, capability.name),
    "",
  ];
  if (properties.length)
    lines.push(
      "| Field | Type | Required | Description |",
      "| --- | --- | --- | --- |",
      ...properties.map(
        ([name, field]) =>
          `| \`${name}\` | ${cell(typeOf(field))} | ${required.has(name) ? "Yes" : ""} | ${cell(describe(field))} |`,
      ),
      "",
    );
  else lines.push("No fields.", "");
  lines.push(
    `\`\`\`json title="${capability.name} arguments"`,
    JSON.stringify(exampleArguments(capability), null, 2),
    "```",
    "",
  );
  return lines;
}

function frontmatter(title: string, description: string) {
  return [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
  ];
}

